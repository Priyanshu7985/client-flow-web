function act(
  project_id: string,
  type: ProjectActivity["type"],
  actor_type: ProjectActivity["actor_type"],
  actor_name: string,
  created_at: string,
  meta: Record<string, unknown> = {},
): ProjectActivity {
  return {
    id: `a-${project_id.slice(-4)}-${type}-${created_at}`,
    project_id,
    type,
    actor_type,
    actor_name,
    meta,
    created_at,
  };
}
